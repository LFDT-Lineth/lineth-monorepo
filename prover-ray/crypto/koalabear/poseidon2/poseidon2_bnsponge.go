// BNSpongeGnarkHasher hashes emulated KoalaBear elements with the width-3
// BN-packed sponge. It must be compiled over BN254.
type BNSpongeGnarkHasher struct {
	api      frontend.API
	koalaAPI *circuit.KoalaBearAPI
	domain   BNSpongeDomain
	buffer   []circuit.Element
}

// NewBNSpongeGnarkHasher creates a new in-circuit width-3 BN-packed sponge
// hasher with the given domain separation mode.
func NewBNSpongeGnarkHasher(api frontend.API, domain BNSpongeDomain) *BNSpongeGnarkHasher {
	checkBNSpongeDomain(domain)
	return &BNSpongeGnarkHasher{api: api, koalaAPI: circuit.NewAPI(api), domain: domain}
}

// Reset clears the buffer.
func (h *BNSpongeGnarkHasher) Reset() { h.buffer = h.buffer[:0] }

// Write appends KoalaBear elements to the buffer.
func (h *BNSpongeGnarkHasher) Write(data ...circuit.Element) {
	h.buffer = append(h.buffer, data...)
}

// WriteOctuplet appends octuplets to the buffer.
func (h *BNSpongeGnarkHasher) WriteOctuplet(data ...circuit.Octuplet) {
	for i := range data {
		h.buffer = append(h.buffer, data[i][:]...)
	}
}

// Sum returns the BN254 digest of the buffered elements. It does not modify
// the buffer. It panics on an empty input. The length n is a compile-time
// constant, so putting it in the capacity costs no constraints.
func (h *BNSpongeGnarkHasher) Sum() frontend.Variable {
	n := len(h.buffer)
	checkBNSpongeLength(n)

	perm, err := stdperm.NewPoseidon2FromParameters(h.api, bnSpongeWidth, bnSpongeFullRounds, bnSpongePartialRounds)
	if err != nil {
		panic(err)
	}

	packed := packKoalaCanonical(h.api, h.koalaAPI, h.buffer)
	s := make([]frontend.Variable, bnSpongeWidth)
	s[bnSpongeCapacityIndex] = n

	for start := 0; start < len(packed); start += bnSpongeRate {
		// overwrite the rate; a missing second chunk is zero
		s[0] = packed[start]
		s[1] = 0
		if start+1 < len(packed) {
			s[1] = packed[start+1]
		}
		if err := perm.Permutation(s); err != nil {
			panic(err)
		}
	}
	return s[bnSpongeOutputIndex]
}

// BNNodeCompressGnark is the in-circuit Merkle node hash for BN-packed trees,
// matching [BNNodeCompress]: gnark std's width-2 Poseidon2 compression.
func BNNodeCompressGnark(api frontend.API, left, right frontend.Variable) frontend.Variable {
	perm, err := stdperm.NewPoseidon2(api)
	if err != nil {
		panic(err)
	}
	return perm.Compress(left, right)
}

// ---------------------------------------------------------------------------

func checkBNSpongeDomain(domain BNSpongeDomain) {
	if domain != BNSpongeLengthInCapacity {
		panic("poseidon2: unsupported BN sponge domain separation mode")
	}
}

func checkBNSpongeLength(n int) {
	if n < bnSpongeMinInputLength {
		panic("poseidon2: BN sponge with length in capacity cannot hash an empty input")
	}
}
