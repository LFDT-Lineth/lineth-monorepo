const INFINITY: [64]u8 = .{0} ** 64;

export fn main() noreturn {
    if (!runChecks()) {
        lineth_accel.zkvm_exit(1);
    }
    lineth_accel.zkvm_exit(0);
}

fn runChecks() bool {
    // ECADD (0x06).
    if (!checkAdd(G2, G3, G5)) return false; // 2G + 3G = 5G
    if (!checkAdd(G, NEG_G, INFINITY)) return false; // G + (-G) = O
    if (!checkAddInvalid(OFF_CURVE, G)) return false; // off-curve operand -> failure

    // ECMUL (0x07). One valid ladder (7*G) plus a cheap invalid case.
    if (!checkMul(G, SCALAR_7, G7)) return false; // 7 * G
    if (!checkMulInvalid(OFF_CURVE, SCALAR_7)) return false; // off-curve point -> failure

    return true;
}

fn checkAdd(p1_bytes: [64]u8, p2_bytes: [64]u8, expected: [64]u8) bool {
    const p1 = G1Point{ .data = p1_bytes };
    const p2 = G1Point{ .data = p2_bytes };
    var out: G1Point = undefined;
    const status = lineth_accel.zkvm_bn254_g1_add(&p1, &p2, &out);
    if (status != .ZKVM_EOK) return false;
    return bytesEqual(out.data[0..], expected[0..]);
}

fn checkAddInvalid(p1_bytes: [64]u8, p2_bytes: [64]u8) bool {
    const p1 = G1Point{ .data = p1_bytes };
    const p2 = G1Point{ .data = p2_bytes };
    var out: G1Point = undefined;
    return lineth_accel.zkvm_bn254_g1_add(&p1, &p2, &out) == .ZKVM_EFAIL;
}

fn checkMul(point_bytes: [64]u8, scalar_bytes: [32]u8, expected: [64]u8) bool {
    const point = G1Point{ .data = point_bytes };
    const scalar = Scalar{ .data = scalar_bytes };
    var out: G1Point = undefined;
    const status = lineth_accel.zkvm_bn254_g1_mul(&point, &scalar, &out);
    if (status != .ZKVM_EOK) return false;
    return bytesEqual(out.data[0..], expected[0..]);
}

fn checkMulInvalid(point_bytes: [64]u8, scalar_bytes: [32]u8) bool {
    const point = G1Point{ .data = point_bytes };
    const scalar = Scalar{ .data = scalar_bytes };
    var out: G1Point = undefined;
    return lineth_accel.zkvm_bn254_g1_mul(&point, &scalar, &out) == .ZKVM_EFAIL;
}

fn bytesEqual(left: []const u8, right: []const u8) bool {
    if (left.len != right.len) return false;
    var i: usize = 0;
    while (i < left.len) : (i += 1) {
        if (left[i] != right[i]) return false;
    }
    return true;
}
